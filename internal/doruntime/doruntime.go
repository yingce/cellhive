// Render copies the platform JS into dir and writes the workerd config.
func Render(dir string, cfg Config) (string, error) {
	if cfg.Addr == "" || cfg.DiskDir == "" || cfg.PlatformJS == "" {
		return "", errors.New("doruntime: Addr, DiskDir and PlatformJS are required")
	}
	for _, a := range cfg.OutboundAllow {
		if !outboundCategories[strings.TrimSpace(a)] {
			return "", fmt.Errorf("doruntime: unknown outbound category %q (want public|private|local)", a)
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	if err := os.MkdirAll(cfg.DiskDir, 0o755); err != nil {
		return "", err
	}
	for _, f := range []string{"host.js", "cellhive-do.js"} {
		data, err := os.ReadFile(filepath.Join(cfg.PlatformJS, f))
		if err != nil {
			return "", err
		}
		if err := os.WriteFile(filepath.Join(dir, f), data, 0o644); err != nil {
			return "", err
		}
	}
	// facades.js is still needed for the queue/scheduled wrapper path; bindings.js
	// provides the RPC capability entrypoints (ADR-090).
	for _, pair := range [][2]string{
		{filepath.Join(cfg.PlatformJS, "..", "platform", "facades.js"), "facades.js"},
		{filepath.Join(cfg.PlatformJS, "..", "platform", "bindings.js"), "bindings.js"},
		{filepath.Join(cfg.PlatformJS, "..", "platform", "bindings-wrapper.js"), "bindings-wrapper.js"},
		{filepath.Join(cfg.PlatformJS, "..", "platform", "log-tail.js"), "log-tail.js"},
		{filepath.Join(cfg.PlatformJS, "..", "platform", "rpc-codec.js"), "rpc-codec.js"},
		{filepath.Join(cfg.PlatformJS, "..", "platform", "telemetry.js"), "telemetry.js"},
	} {
		data, err := os.ReadFile(pair[0])
		if err != nil {
			return "", err
		}
		if err := os.WriteFile(filepath.Join(dir, pair[1]), data, 0o644); err != nil {
			return "", err
		}
	}
	tpl, err := template.New("capnp").Parse(capnpTemplate)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := tpl.Execute(&buf, cfg); err != nil {
		return "", err
	}
	path := filepath.Join(dir, "do-runtime.capnp")
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

// Run starts workerd with the rendered config and blocks until it exits or ctx is
// cancelled.
func Run(ctx context.Context, workerdBin, capnpPath string) error {
	cmd := exec.CommandContext(ctx, workerdBin, "serve", "--experimental", capnpPath)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

// FindWorkerd locates the workerd binary (shared locator).
func FindWorkerd() (string, error) { return workerdbin.Find() }
