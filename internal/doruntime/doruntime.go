// Package doruntime renders and launches the do-runtime workerd process
// (docs/durable-objects.md): a native Durable Object host actor that runs tenant
// Durable Objects as facets with local-disk SQLite storage (ADR-077).
package doruntime

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"text/template"

	"cellhive/internal/workerdbin"
)

// outboundCategories are the workerd network categories a tenant outbound policy
// may name.
var outboundCategories = map[string]bool{"public": true, "private": true, "local": true}

// OutboundAllowList renders the tenant facet outbound policy for the capnp
// config. Empty defaults to "public" (ADR-130).
func (c Config) OutboundAllowList() string {
	if len(c.OutboundAllow) == 0 {
		return `"public"`
	}
	parts := make([]string, 0, len(c.OutboundAllow))
	for _, a := range c.OutboundAllow {
		parts = append(parts, strconv.Quote(strings.TrimSpace(a)))
	}
	return strings.Join(parts, ", ")
}

// WsAllowList renders the facet DO-WebSocket binding's network policy (the
// tenant-visible CH_DO_CONNECT binding). Empty falls back to public+private
// for back-compat; production narrows it to the runtime cluster's addresses.
func (c Config) WsAllowList() string {
	parts := make([]string, 0, len(c.WsAllow))
	for _, a := range c.WsAllow {
		if a = strings.TrimSpace(a); a != "" {
			parts = append(parts, strconv.Quote(a))
		}
	}
	if len(parts) == 0 {
		return `"public", "private"`
	}
	return strings.Join(parts, ", ")
}

// Config configures one do-runtime instance.
type Config struct {
	// CellURL/CellToken are the cell-agent base URL and internal-role token
	// (used to fetch tenant bundles and to authenticate /v1/do/invoke).
	CellURL   string
	CellToken string
	// Addr is the workerd HTTP listen address, e.g. "*:8788".
	Addr string
	// DiskDir holds the per-class Durable Object SQLite storage.
	DiskDir string
	// PlatformJS is the directory holding host.js.
	PlatformJS string
	// FacadesJS is the path to facades.js (tenant binding facades). When empty,
	// it is derived from PlatformJS (../platform/facades.js).
	FacadesJS string
	// AIURL/AIKey configure the BYO OpenAI-compatible AI binding endpoint.
	AIURL string
	AIKey string
	// LogToken authorizes the bounded log-ingest endpoint (loaded workers).
	LogToken string
	// DoTicketSecret verifies short-lived DO owner tickets (ADR-105). Empty
	// disables ticket auth (internal token only).
	DoTicketSecret string
	// DoLeaseS is the DO owner lease TTL in seconds (empty = runtime default 30).
	// Longer reduces renew churn; shorter fails over faster.
	DoLeaseS string
	// WsAllow is the network policy for the tenant-visible CH_DO_CONNECT binding
	// (DO WebSocket upgrades only). Empty falls back to public+private.
	WsAllow []string
	// OutboundAllow is the tenant DO facets' outbound network policy (ADR-130).
	// Empty = ["public"]. Facets may reach the allowed ranges via
	// `cloudflare:sockets connect()`; a Durable Object can hold the socket across
	// requests, which is how tenant code pools connections locally.
	OutboundAllow []string
	// DOObjectIndex mirrors the runtime object registry into the bucket so a cold
	// start can enumerate objects without asking every runtime (ADR-108).
	DOObjectIndex bool
	// NodeID/Advertise identify this do-runtime task in owner records.
	NodeID    string
	Advertise string
	// PreventEviction selects the resident (true) or evictable (false) host
	// actor configuration (ADR-078). Default is resident.
	PreventEviction bool
	// GateURL is the do-supervisor base URL; when set, responses are gated on
	// capture durability (ADR-083). Empty disables the gate.
	GateURL string
}

