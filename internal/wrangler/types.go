package wrangler

import (
	"fmt"
	"sort"
	"strings"
)

// EnvTypes generates the configuration-derived part of a TypeScript Env
// declaration. Runtime API declarations remain supplied by the project's
// Cloudflare Workers types package or by official `wrangler types`.
func EnvTypes(d *Deploy, interfaceName string) ([]byte, error) {
	if !tsIdentifier(interfaceName) || reservedTSWord[interfaceName] {
		return nil, fmt.Errorf("invalid TypeScript interface name %q", interfaceName)
	}
	if len(d.UnknownFields) != 0 {
		return nil, fmt.Errorf("unsupported Wrangler config fields: %s", strings.Join(d.UnknownFields, ", "))
	}
	types := map[string]string{}
	for name := range d.Vars {
		types[name] = "string"
	}
	for _, b := range d.Bindings {
		var typ string
		switch b.Type {
		case "kv":
			typ = "KVNamespace"
		case "d1":
			typ = "D1Database"
		case "r2":
			typ = "R2Bucket"
		case "queue":
			typ = "Queue"
		case "workflow":
			typ = "Workflow"
		case "do":
			typ = "DurableObjectNamespace"
		case "service":
			typ = "Fetcher"
		case "ai":
			typ = "Ai"
		case "hyperdrive":
			typ = "Hyperdrive"
		case "vectorize":
			typ = "VectorizeIndex"
		default:
			return nil, fmt.Errorf("unsupported binding type %q", b.Type)
		}
		if b.Name == "" {
			return nil, fmt.Errorf("binding name is required")
		}
		if _, exists := types[b.Name]; exists {
			return nil, fmt.Errorf("duplicate Env name %q", b.Name)
		}
		types[b.Name] = typ
	}
	if d.AssetsBinding != "" {
		if _, exists := types[d.AssetsBinding]; exists {
			return nil, fmt.Errorf("duplicate Env name %q", d.AssetsBinding)
		}
		types[d.AssetsBinding] = "Fetcher"
	}
	names := make([]string, 0, len(types))
	for name := range types {
		names = append(names, name)
	}
	sort.Strings(names)
	var out strings.Builder
	out.WriteString("// Generated by cellhive types. Runtime types: @cloudflare/workers-types.\n")
	out.WriteString("interface " + interfaceName + " {\n")
	for _, name := range names {
		key := name
		if !tsIdentifier(name) {
			key = fmt.Sprintf("%q", name)
		}
		out.WriteString("\t" + key + ": " + types[name] + ";\n")
	}
	out.WriteString("}\n")
	return []byte(out.String()), nil
}

var reservedTSWord = map[string]bool{
	"class": true, "default": true, "enum": true, "export": true,
	"extends": true, "function": true, "import": true, "interface": true,
	"new": true, "type": true, "var": true,
}

func tsIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if r == '_' || r == '$' || r >= 'A' && r <= 'Z' || r >= 'a' && r <= 'z' || i > 0 && r >= '0' && r <= '9' {
			continue
		}
		return false
	}
	return true
}
